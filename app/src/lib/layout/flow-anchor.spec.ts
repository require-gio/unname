// @vitest-environment jsdom
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { renderAsync } from 'docx-preview';
import { describe, expect, it } from 'vitest';
import type { LayoutUnit } from '#lib/sidecar/api.gen.js';
import type { Segment } from '#lib/ui/segments.js';
import {
	abbilden,
	displayedText,
	anchorElements,
	unitOn,
	unitRawText,
	replace,
	pointFor,
	SOURCE_ATTRIBUTE,
	sourceOffset,
	partsPerUnit,
	vereinfachen,
	ADDITION_ATTRIBUTE
} from './flow-anchor.js';

/**
 * Verify that each replacement appears exactly where it is stored in the
 * saved file. The test renders the saved DOCX with docx-preview and compares
 * each unit side-by-side. Paragraphs are not simplified in the corpus.
 *
 * Fixtures are generated by `scripts/layout-corpus.py --smoke` using the real
 * sidecar code: a preview copy of the letter and a preview copy of the file
 * that the export saved with the same replacements.
 */

const FIXTURES = resolve(import.meta.dirname, '../../../tests/smoke/fixtures/layout');

interface Place {
	id: string;
	value: string;
	type: string;
	after?: string;
}

const LETTER = JSON.parse(readFileSync(`${FIXTURES}/letter.json`, 'utf8')) as {
	text: string;
	layout: { units: LayoutUnit[] };
	places: Place[];
};
const UNITS = LETTER.layout.units;

function section(place: Place): { start: number; end: number } {
	const ab = place.after ? LETTER.text.indexOf(place.after) : 0;
	const start = LETTER.text.indexOf(place.value, ab);
	return { start, end: start + place.value.length };
}

/** Same code as `smoke_code` in the corpus script. */
function code(place: Place): string {
	return `<<${place.type}_${place.id.slice(2).padEnd(8, '0').slice(0, 8)}>>`;
}

async function render(file: string): Promise<HTMLElement> {
	const wurzel = document.createElement('div');
	const stile = document.createElement('div');
	document.body.append(stile, wurzel);
	await renderAsync(readFileSync(`${FIXTURES}/${file}`), wurzel, stile, {
		breakPages: true,
		ignoreLastRenderedPageBreak: false,
		renderHeaders: true,
		renderFooters: true,
		renderComments: false,
		renderChanges: false,
		useBase64URL: true,
		experimental: false
	});
	return wurzel;
}

function replacement(text: string, start: number, end: number): HTMLElement {
	const element = document.createElement('span');
	element.setAttribute(SOURCE_ATTRIBUTE, `${start}:${end}`);
	element.textContent = text;
	return element;
}

/** Run format for a node – class and style of the span that contains it. */
function runFormat(node: Node): string {
	let element = node.nodeType === Node.TEXT_NODE ? node.parentElement : (node as Element);
	while (element?.hasAttribute(SOURCE_ATTRIBUTE)) element = element.parentElement;
	const run = element?.closest('span');
	return `${run?.className ?? ''}|${run?.getAttribute('style') ?? ''}|${run?.parentElement?.localName}`;
}

function textNodeWith(wurzel: Node, text: string): Text | null {
	const gang = document.createTreeWalker(wurzel, NodeFilter.SHOW_TEXT);
	for (let node = gang.nextNode(); node; node = gang.nextNode()) {
		if ((node as Text).data.includes(text)) return node as Text;
	}
	return null;
}

describe('Korpus-Brief (docx-preview, jsdom)', () => {
	it('maps each unit – no simplified paragraph, header and footer on every page', async () => {
		const wurzel = await render('letter-preview.docx');
		expect(wurzel.querySelector('header')).not.toBeNull();
		for (const unit of UNITS) {
			const anchor = anchorElements(wurzel, unit.anchor);
			expect(anchor.length, unit.anchor).toBeGreaterThan(0);
			const text = LETTER.text.slice(unit.start, unit.end);
			for (const element of anchor) {
				const figure = abbilden(element, wurzel, text, unit.start);
				expect(figure, `${unit.anchor}: ${text}`).not.toBeNull();
				expect(displayedText(figure!)).toBe(text);
			}
		}
	});

	it('View = File: each replacement stays in its unit, in the same run', async () => {
		const view = await render('letter-preview.docx');
		const file = await render('letter-result-preview.docx');
		const segments: Segment[] = LETTER.places.map((place) => ({
			kind: 'code',
			text: code(place),
			id: place.id,
			source: section(place)
		}));
		const parts = partsPerUnit(UNITS, segments, LETTER.text);
		expect([...parts.values()].flat()).toHaveLength(LETTER.places.length);

		for (const [index, list] of parts) {
			const unit = UNITS[index];
			const text = LETTER.text.slice(unit.start, unit.end);
			for (const anchor of anchorElements(view, unit.anchor)) {
				const figure = abbilden(anchor, view, text, unit.start)!;
				replace(
					figure,
					list.map((part) => ({ ...part, element: replacement(part.text, part.start, part.end) }))
				);
			}
		}

		for (const unit of UNITS) {
			const text = LETTER.text.slice(unit.start, unit.end);
			const visibleAnchors = anchorElements(view, unit.anchor);
			const saved = anchorElements(file, unit.anchor);
			expect(visibleAnchors.length, unit.anchor).toBe(saved.length);
			visibleAnchors.forEach((anchor, i) => {
				const figure = abbilden(anchor, view, text, unit.start);
				expect(figure, unit.anchor).not.toBeNull();
				expect(displayedText(figure!), unit.anchor).toBe(unitRawText(saved[i], file));
			});
		}

		// The code is in the run where the position starts – both in the file and in
		// the view (bold first name, hyperlink text, header and footer).
		for (const place of LETTER.places) {
			const inFile = textNodeWith(file, code(place));
			const inView = [...view.querySelectorAll(`[${SOURCE_ATTRIBUTE}]`)].find(
				(element) => element.textContent === code(place)
			);
			expect(inFile, place.id).not.toBeNull();
			expect(inView, place.id).toBeDefined();
			expect(runFormat(inView!), place.id).toBe(runFormat(inFile!));
		}
	});

	it('Mark: DOM positions map to source offsets across code', async () => {
		const wurzel = await render('letter-preview.docx');
		const index = unitOn(UNITS, LETTER.text.indexOf('Rueckfragen'));
		const unit = UNITS[index];
		const text = LETTER.text.slice(unit.start, unit.end);
		const [anchor] = anchorElements(wurzel, unit.anchor);
		const mail = LETTER.text.indexOf('shop@', unit.start);
		const figure = abbilden(anchor, wurzel, text, unit.start)!;
		replace(figure, [
			{
				start: mail,
				end: mail + 27,
				element: replacement('<<EMAIL_ADDRESS_mail0000>>', mail, mail + 27)
			}
		]);
		const fresh = abbilden(anchor, wurzel, text, unit.start)!;
		const on = textNodeWith(wurzel, 'Rueckfragen an ')!;
		expect(sourceOffset(fresh, on, 0, 'start')).toBe(unit.start);
		expect(sourceOffset(fresh, on, 4, 'start')).toBe(unit.start + 4);
		const element = wurzel.querySelector(`[${SOURCE_ATTRIBUTE}]`)!;
		expect(sourceOffset(fresh, element.firstChild!, 3, 'end')).toBe(mail + 27);
		expect(sourceOffset(fresh, element.firstChild!, 0, 'start')).toBe(mail);
		const oder = textNodeWith(wurzel, ' oder')!;
		expect(sourceOffset(fresh, oder, 5, 'end')).toBe(mail + 27 + 5);
		// A position between nodes (element boundary) belongs to the following piece.
		expect(sourceOffset(fresh, element.parentNode!, 0, 'start')).toBeLessThanOrEqual(mail);
	});
});

/** Small documents in the form generated by docx-preview. */
function dom(html: string): HTMLElement {
	const wurzel = document.createElement('div');
	wurzel.innerHTML = html;
	return wurzel;
}

describe('Match with equivalence table', () => {
	it('Tab, line break, w:cr, protected hyphen, soft hyphen', () => {
		const wurzel = dom(
			'<p><span id="unn_u0"></span><span>A</span><span>\u2003</span><span>B</span><br><span>C</span><span>D</span><wbr><span>E\u00adF</span></p>'
		);
		const figure = abbilden(wurzel.querySelector('#unn_u0')!, wurzel, 'A\tB\nC\nD-EF', 10)!;
		expect(figure).not.toBeNull();
		expect(figure.pieces.map((piece) => piece.kind)).toEqual([
			'text',
			'text',
			'text',
			'character',
			'text',
			'text',
			'character',
			'text'
		]);
		// "E\u00adF": the soft hyphen is between E and F, no offset.
		const last = figure.pieces.at(-1)!;
		expect(last.kind === 'text' && last.offsets).toEqual([18, 19, 19, 20]);
	});

	it('Paragraph across a page break continues; header/footer not counted', () => {
		const wurzel = dom(
			'<section><article><p><span id="unn_u0"></span><span>Erste Hälfte </span></p></article><footer><p><span id="unn_u2"></span><span>Fuß</span></p></footer></section>' +
				'<section><header><p><span id="unn_u3"></span><span>Kopf</span></p></header><article><p><span>zweite Hälfte</span></p><p><span id="unn_u1"></span><span>Weiter</span></p></article></section>'
		);
		const anchor = wurzel.querySelector('#unn_u0')!;
		const figure = abbilden(anchor, wurzel, 'Erste Hälfte zweite Hälfte', 0);
		expect(figure).not.toBeNull();
		expect(displayedText(figure!)).toBe('Erste Hälfte zweite Hälfte');
		// The header ends at its own boundary.
		const header = abbilden(wurzel.querySelector('#unn_u3')!, wurzel, 'Kopf', 40);
		expect(header && displayedText(header)).toBe('Kopf');
	});

	it('If text deviates, no mapping – simplified it matches again', () => {
		const wurzel = dom(
			'<p><span id="unn_u0"></span><span>Hallo</span><span>Feld</span></p><p><span id="unn_u1"></span><span>Nächster</span></p>'
		);
		const anchor = wurzel.querySelector('#unn_u0')!;
		expect(abbilden(anchor, wurzel, 'Hallo', 0)).toBeNull();
		expect(abbilden(anchor, wurzel, 'Hallo Welt', 0)).toBeNull();
		vereinfachen(anchor, wurzel, 'Hallo\tWelt\nzwei');
		const figure = abbilden(anchor, wurzel, 'Hallo\tWelt\nzwei', 0);
		expect(figure && displayedText(figure)).toBe('Hallo\tWelt\nzwei');
		// The next paragraph remains untouched.
		expect(abbilden(wurzel.querySelector('#unn_u1')!, wurzel, 'Nächster', 17)).not.toBeNull();
	});

	it('Replace across two runs: code lands in first run, additions ignored', () => {
		const wurzel = dom(
			'<p><span id="unn_u0"></span><span class="fett">Max </span><span class="normal">Mustermann</span><span>, Wien</span></p>'
		);
		const anchor = wurzel.querySelector('#unn_u0')!;
		const figure = abbilden(anchor, wurzel, 'Max Mustermann, Wien', 100)!;
		const code = replacement('<<PERSON_1>>', 100, 114);
		const number = document.createElement('sup');
		number.setAttribute(ADDITION_ATTRIBUTE, '');
		number.textContent = '1';
		code.after(number);
		replace(figure, [{ start: 100, end: 114, element: code }]);
		code.after(number);
		expect(code.parentElement?.className).toBe('fett');
		expect(wurzel.textContent).toBe('<<PERSON_1>>1, Wien');
		const fresh = abbilden(anchor, wurzel, 'Max Mustermann, Wien', 100);
		expect(fresh && displayedText(fresh)).toBe('<<PERSON_1>>, Wien');
		// End of a range at the unit's end, start at the beginning.
		expect(pointFor(fresh!, 120, 'end')).toEqual({
			node: textNodeWith(wurzel, ', Wien'),
			versatz: 6
		});
		expect(pointFor(fresh!, 100, 'start')).toEqual({
			node: code.parentElement,
			versatz: [...code.parentElement!.childNodes].indexOf(code)
		});
	});
});

describe('partsPerUnit', () => {
	const units: LayoutUnit[] = [
		{ anchor: 'unn_u0', start: 0, end: 5 },
		{ anchor: 'unn_u1', start: 6, end: 11 }
	];
	const text = 'Hallo\nWelt!';

	it('splits source text per unit, code only in first part', () => {
		const parts = partsPerUnit(
			units,
			[
				{ kind: 'plain', text: 'Ha', source: { start: 0, end: 2 } },
				{ kind: 'selection', text: 'llo\nWe', source: { start: 2, end: 8 } },
				{ kind: 'code', text: '<<X>>', id: 'f', source: { start: 3, end: 9 } }
			],
			text
		);
		expect(parts.get(0)?.map((part) => [part.segment.kind, part.text, part.first])).toEqual([
			['selection', 'llo', true],
			['code', '<<X>>', true]
		]);
		expect(parts.get(1)?.map((part) => [part.segment.kind, part.text, part.first])).toEqual([
			['selection', 'We', false],
			['code', '', false]
		]);
	});

	it('unitOn: binary search over starts', () => {
		expect(unitOn(units, 0)).toBe(0);
		expect(unitOn(units, 5)).toBe(0);
		expect(unitOn(units, 6)).toBe(1);
		expect(unitOn([], 3)).toBe(-1);
	});
});
