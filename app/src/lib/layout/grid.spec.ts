describe('Tiles', () => {
	const lines = new Axis([20, 20, 20, 20]);
	const columns = new Axis([50, 50, 0, 50]);
	const cells: Cell[] = [
		[0, 0, 'Titel', 0, -1, -1],
		[1, 1, 'b', 0, -1, -1],
		[1, 3, 'd', 0, -1, -1]
	];
	const storage = new CellStorage();
	storage.drop(0, cells);

	it('draw each visible cell once, merges with full area', () => {
		const verbunde = new Verbunde([[0, 0, 0, 1]]);
		const list = tiles(
			{ lines: [0, 1], columns: [0, 3] },
			lines,
			columns,
			verbunde,
			(z) => storage.line(z),
			{ x: 0, y: 0 }
		);
		expect(list.map((k) => [k.line, k.column, k.x, k.width, k.cell?.[DISPLAY]])).toEqual([
			[0, 0, 0, 100, 'Titel'],
			[0, 3, 100, 50, undefined],
			[1, 0, 0, 50, undefined],
			[1, 1, 50, 50, 'b'],
			[1, 3, 100, 50, 'd']
		]);
	});

	it('draw a merge that extends outside the window', () => {
		const verbunde = new Verbunde([[0, 0, 2, 1]]);
		const list = tiles(
			{ lines: [1, 2], columns: [1, 3] },
			lines,
			columns,
			verbunde,
			(z) => storage.line(z),
			{ x: 50, y: 20 }
		);
		const anchor = list.find((k) => k.line === 0 && k.column === 0)!;
		expect([anchor.x, anchor.y, anchor.width, anchor.height]).toEqual([-50, -20, 100, 60]);
		expect(list.some((k) => k.line === 1 && k.column === 1)).toBe(false);
	});
});

describe('Segments of a cell', () => {
	const text = 'Max Mustermann\tWien';
	const segments: Segment[] = [
		{ kind: 'code', text: '<<P>>', id: 'a', source: { start: 0, end: 14 } },
		{ kind: 'plain', text: '\tWien', source: { start: 14, end: 19 } }
	];
	const index = new SegmentIndex(segments);

	it('cuts text at the cell border, a code remains whole', () => {
		expect(index.in(0, 14)).toEqual([segments[0]]);
		expect(index.in(15, 19)).toEqual([
			{ kind: 'plain', text: 'Wien', source: { start: 15, end: 19 } }
		]);
	});

	it('shows the source text where a position is or the display matches it', () => {
		expect(cellContent([0, 0, 'Max Mustermann', 0, 0, 14], index, text)).toEqual([segments[0]]);
		expect(segmentText(cellContent([0, 1, 'Wien', 0, 15, 19], index, text)!)).toBe('Wien');
		// Formatted value (number, date): no source text, no marking.
		expect(cellContent([0, 1, 'WIEN', 0, 15, 19], index, text)).toBeNull();
		expect(cellContent([0, 1, 'x', 0, -1, -1], index, text)).toBeNull();
	});
});

describe('View = file (cell comparison, A-27)', () => {
	for (const [name, probe] of [
		['XLSX', CUSTOMERS],
		['CSV', CUSTOMERS_CSV]
	] as const) {
		it(`${name}: each cell shows the text of the saved file`, () => {
			const index = new SegmentIndex(result(probe));
			const saved = new Map(
				probe.saved.map(([sheet, line, column, value]) => [`${sheet}:${line}:${column}`, value])
			);
			let replaced = 0;
			probe.cells.forEach((cells, sheet) => {
				for (const cell of cells) {
					if (cell[START] < 0) continue;
					const file = saved.get(`${sheet}:${cell[0]}:${cell[1]}`);
					const content = cellContent(cell, index, probe.text);
					const source = probe.text.slice(cell[START], cell[END]);
					if (content?.some((segment) => segment.kind === 'code')) replaced += 1;
					// The view shows the source text with codes – or the formatted value of a
					// unchanged cell; then the file contains the unchanged source text.
					expect(content ? segmentText(content) : source).toBe(file);
				}
			});
			expect(replaced).toBe(probe.places.length);
		});
	}

	it('XLSX: numbers and dates are formatted, text stays source', () => {
		const [customers] = CUSTOMERS.cells;
		const cell = (z: number, s: number) => customers.find((c) => c[0] === z && c[1] === s)!;
		expect(cell(2, 3)[DISPLAY]).toBe('1.234,50 €');
		expect(cell(2, 5)[DISPLAY]).toBe('01.03.2024');
		const index = new SegmentIndex(result(CUSTOMERS));
		expect(cellContent(cell(2, 3), index, CUSTOMERS.text)).toBeNull();
		expect(segmentText(cellContent(cell(2, 2), index, CUSTOMERS.text)!)).toBe('Wien');
	});
});

describe('Stylesheet', () => {
	it('adds styles as classes under the root', () => {
		const css = styleRules('[data-grid="x"]', CUSTOMERS.layout.styles);
		expect(css).toContain('[data-grid="x"] .s0{');
		expect(css).toMatch(
			/\.s\d+\{font-weight:700;background-color:#F2F2F2;.*border-bottom:1px solid #1F1846/
		);
		expect(css).toMatch(/\.s\d+\{font-weight:700;font-size:18\.6+\dpx;justify-content:safe center/);
	});

	it('includes only reviewed values from the file in the stylesheet', () => {
		const css = styleRules('.w', [
			{
				font: 'Arial"}body{display:none',
				color: 'red;background:url(x)',
				fill: '#12345G',
				border: { left: ['thin', 'blue}'] }
			}
		]);
		expect(css).not.toContain('url(');
		expect(css).not.toContain('display:none');
		expect(css).not.toContain('font-family');
		expect(css).toContain('border-left:1px solid var(--paper-ink)');
		expect(css.split('{').length).toBe(2);
	});
});

describe('Loading in blocks', () => {
	it('needs the window blocks and the fixed rows', () => {
		expect(requiredBlocks([1200, 1300], 2, 10_000)).toEqual([0, 2]);
		expect(requiredBlocks([450, 520], 0, 10_000)).toEqual([0, 1]);
		expect(requiredBlocks([0, -1], 0, 3)).toEqual([0]);
		expect(requiredBlocks([0, -1], 0, 0)).toEqual([]);
	});

	it('requests each block once and reports failures', async () => {
		const fetch = vi.fn(async (_sheet: number, by: number) => {
			if (by === 500) throw new Error('weg');
			return [[by, 0, 'a', 0, -1, -1]] as Cell[];
		});
		const loaded = vi.fn();
		const error = vi.fn();
		const lader = new CellLader(fetch, loaded, error);
		await Promise.all([lader.block(0, 0, 'de'), lader.block(0, 0, 'de')]);
		await lader.block(0, 0, 'de');
		expect(fetch).toHaveBeenCalledTimes(1);
		expect(fetch).toHaveBeenCalledWith(0, 0, 499, 'de');
		expect(lader.storage(0, 'de').line(0)).toEqual([[0, 0, 'a', 0, -1, -1]]);
		// A different language uses a separate storage.
		expect(lader.storage(0, 'en').line(0)).toBeUndefined();
		await lader.block(0, 1, 'de');
		expect(loaded).toHaveBeenCalledTimes(1);
		expect(error).toHaveBeenCalledTimes(1);
	});
});
