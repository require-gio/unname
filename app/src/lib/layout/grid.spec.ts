/**
 * Test layout generation: the XLSX includes column widths, row heights,
 * merged cells and formatting; substitutions appear in cells that the
 * export modifies (cell comparison with saved file).
 *
 * Fixtures are generated by `scripts/layout-corpus.py --smoke` using the real
 * sidecar code: table model, cells and the file cells that the export saved
 * with the same substitutions.
 */

const FIXTURES = resolve(import.meta.dirname, '../../../tests/smoke/fixtures/layout');

interface Place {
	id: string;
	value: string;
	type: string;
	after?: string;
	question?: unknown;
}

interface Probe {
	text: string;
	layout: { sheets: LayoutSheet[]; styles: LayoutCellStyle[] };
	cells: Cell[][];
	places: Place[];
	saved: [number, number, number, string][];
}

const load = (name: string) =>
	JSON.parse(readFileSync(`${FIXTURES}/${name}.json`, 'utf8')) as Probe;
const CUSTOMERS = load('customers');
const CUSTOMERS_CSV = load('customers-csv');

function section(probe: Probe, place: Place): { start: number; end: number } {
	const ab = place.after ? probe.text.indexOf(place.after) : 0;
	const start = probe.text.indexOf(place.value, ab);
	return { start, end: start + place.value.length };
}

/** Same logic as `smoke_code` in the corpus script. */
function code(place: Place): string {
	return `<<${place.type}_${place.id.slice(2).padEnd(8, '0').slice(0, 8)}>>`;
}

/** Build segments: code tokens at positions, plain text between with source ranges. */
function result(probe: Probe): Segment[] {
	const places = probe.places
		.map((place) => ({ place, ...section(probe, place) }))
		.sort((a, b) => a.start - b.start);
	const segments: Segment[] = [];
	let cursor = 0;
	for (const { place, start, end } of places) {
		if (start > cursor) {
			segments.push({
				kind: 'plain',
				text: probe.text.slice(cursor, start),
				source: { start: cursor, end: start }
			});
		}
		segments.push({
			kind: 'code',
			text: code(place),
			id: place.id,
			type: place.type,
			original: place.value,
			operable: true,
			source: { start, end }
		});
		cursor = end;
	}
	segments.push({
		kind: 'plain',
		text: probe.text.slice(cursor),
		source: { start: cursor, end: probe.text.length }
	});
	return segments;
}

describe('Axis', () => {
	const axis = new Axis([10, 0, 20, 5]);

	it('sums sizes, hidden entries have size 0', () => {
		expect([0, 1, 2, 3, 4].map((i) => axis.pos(i))).toEqual([0, 10, 10, 30, 35]);
		expect(axis.length).toBe(35);
		expect(axis.size(1)).toBe(0);
	});

	it('finds element at a position and skips hidden entries', () => {
		expect(axis.on(0)).toBe(0);
		expect(axis.on(9.9)).toBe(0);
		expect(axis.on(10)).toBe(2);
		expect(axis.on(34)).toBe(3);
		expect(axis.on(1000)).toBe(3);
	});

	it('returns the viewport with margin', () => {
		expect(axis.viewport(12, 31)).toEqual([2, 3]);
		expect(axis.viewport(12, 20, 1)).toEqual([1, 3]);
		expect(new Axis([]).viewport(0, 100)).toEqual([0, -1]);
	});

	it('handles 10 000 lines without iteration', () => {
		const lines = new Axis(Array.from({ length: 10_000 }, () => 20));
		expect(lines.length).toBe(200_000);
		expect(lines.viewport(150_000, 150_600, 8)).toEqual([7492, 7537]);
	});
});

