test('Word: without saved line breaks view breaks after pages', async ({ context, page }) => {
	await harness(context, {
		entries: () => [ENTRY],
		sidecar: (method, path) => {
			if (path === '/entries/e-w' && method === 'GET') return ENTRY;
			if (path === '/entries/e-w/progress') {
				return { entry_id: 'e-w', status: 'review', files: [], totals: {}, done: 1, total: 1 };
			}
			if (!path.startsWith('/jobs/j-w/')) return undefined;
			if (path.endsWith('/findings')) {
				return {
					...findings(),
					text: LANG.text,
					confirmed: [],
					findings: [],
					blocks: [{ index: 0, start: 0, end: LANG.text.length, kind: 'paragraph', page: null }],
					counts: {
						confirmed: 0,
						suspicious: 0,
						total: 0,
						by_entity: {},
						by_category: {},
						questions: 0
					}
				};
			}
			if (path.endsWith('/layout')) return { job_id: 'j-w', ...LANG.layout };
			if (path.endsWith('/layout/document')) {
				return new Roh(readFileSync(`${FIXTURES}/long-preview.docx`), DOCX);
			}
			return undefined;
		}
	});
	await open(page, '/entry/e-w/review');
	const doc = island(page);
	await expect(doc.locator('section.docx').first()).toBeVisible();

	const docPages = await doc.locator('section.docx').evaluateAll((list) =>
		list.map((docPage) => ({
			height: docPage.getBoundingClientRect().height,
			soll:
				parseFloat(getComputedStyle(docPage).minHeight) *
				(Number(getComputedStyle(docPage.ownerDocument.documentElement).zoom) || 1),
			fuss: docPage.querySelector(':scope > footer')?.textContent ?? '',
			header: docPage.querySelector(':scope > header')?.textContent ?? ''
		}))
	);
	expect(docPages.length).toBeGreaterThan(3);
	for (const docPage of docPages) {
		// No page exceeds its page size; each has header and footer.
		expect(docPage.height).toBeLessThanOrEqual(docPage.soll + 2);
		expect(docPage.header).toContain('Moebelhaus Online Shop');
		expect(docPage.fuss).toContain('Ihr Online Team');
	}
	// The long table is separated between rows, no row is missing.
	const lines = await doc
		.locator('table')
		.evaluateAll((tables) => tables.reduce((sum, t) => sum + t.querySelectorAll('tr').length, 0));
	expect(lines).toBe(3 + 80);
	expect(await doc.locator('table').count()).toBeGreaterThan(2);
	// No paragraph simplification: anchors remain renderable after reflow.
	await expect(page.getByRole('note')).toHaveCount(0);
	await expect(doc.getByText('Mit freundlichen Gruessen')).toBeAttached();
});
