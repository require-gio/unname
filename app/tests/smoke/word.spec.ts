test('Word page-faithful: engine pages, codes with menu, space shows the original', async ({
	context,
	page
}) => {
	const { capture } = await wordHarness(context, { pageFaithful: 'da' });
	await open(page, '/entry/e-w/review');
	await islandReady(page);
	await page.getByRole('radio', { name: 'Seitentreu' }).click();

	const docPages = page.locator('article[data-column="pages"]');
	await expect(docPages).toBeVisible();
	await expect(page.locator('iframe')).toHaveCount(0);
	await expect(page.getByText('Seiten gesetzt mit docxide-pdf 0.20.1')).toBeVisible();
	// The result is for the exact state the card specifies.
	await expect
		.poll(() =>
			capture.requests.some(
				(request) =>
					request.path === '/jobs/j-w/layout/paged/0' &&
					request.search.includes('side=result&revision=1')
			)
		)
		.toBe(true);
	// Each place has its marker on the page – also in header and footer.
	for (const place of LETTER.places) {
		await expect(docPages.locator(`g[data-id="${place.id}"]`)).toHaveCount(1);
	}
	await expect(page.getByRole('note')).toHaveCount(0);

	const name = docPages.getByRole('button', { name: /Mustermann/ });
	await name.click();
	await expect(page.getByRole('menu')).toBeVisible();
	await page.keyboard.press('Escape');
	await expect(page.getByRole('menu')).toBeHidden();

	await board(page, 'layout-page-faithful');

	// Space: the pages of the original.
	await page.locator('body').click({ position: { x: 5, y: 400 } });
	await page.keyboard.down('Space');
	await expect
		.poll(() =>
			capture.requests.some(
				(request) =>
					request.path === '/jobs/j-w/layout/paged/0' && request.search.includes('side=original')
			)
		)
		.toBe(true);
	await page.keyboard.up('Space');

	// the entry owns its representation; new entries keep the device default.
	await expect
		.poll(() =>
			capture.requests.some(
				(request) =>
					request.method === 'PUT' &&
					request.path === '/entries/e-w/view' &&
					(request.body as { representation?: string })?.representation === 'faithful'
			)
		)
		.toBe(true);
	expect(await page.evaluate(() => localStorage.getItem('unname.appearance'))).toBeNull();
});

