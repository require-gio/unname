/**
 * Verify that the DOCX letter renders with pages, table, header and footer.
 * Each replacement appears in the DOM at the same location as in the exported file
 * (unit-compare with the saved file `fluss-anker.spec.ts`). No paragraph simplification
 * occurs in the corpus.
 *
 * This tests the app view: the iframe island without scripts, codes as buttons with a shared
 * menu, selection via the browser, side-by-side view, space key, Alt+N, and fallback to
 * plain text when the preview copy is missing.
 *
 * Layout map and preview copy are generated by the real sidecar script
 * (`scripts/layout-corpus.py --smoke`).
 */

test.describe.configure({ timeout: 90_000 });

const FIXTURES = resolve(import.meta.dirname, 'fixtures/layout');
const DOCX = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';

interface Place {
	id: string;
	value: string;
	type: string;
	category: string;
	after?: string;
	question?: { kind: 'uncertain'; n: number };
}

const LETTER = JSON.parse(readFileSync(`${FIXTURES}/letter.json`, 'utf8')) as {
	text: string;
	layout: Record<string, unknown>;
	places: Place[];
};
const PREVIEW = readFileSync(`${FIXTURES}/letter-preview.docx`);
/** Generate page-faithful maps and images using the Office engine (`layout-corpus.py --smoke`). */
const PAGE_FAITHFUL = JSON.parse(
	readFileSync(`${FIXTURES}/letter-page-faithful.json`, 'utf8')
) as Record<'original' | 'result', Record<string, unknown>>;
const PAGE_FAITHFUL_IMAGE = {
	original: readFileSync(`${FIXTURES}/letter-page-faithful-original-0.png`),
	result: readFileSync(`${FIXTURES}/letter-page-faithful-result-0.png`)
};

function section(place: Place): { start: number; end: number } {
	const ab = place.after ? LETTER.text.indexOf(place.after) : 0;
	const start = LETTER.text.indexOf(place.value, ab);
	return { start, end: start + place.value.length };
}

function code(place: Place): string {
	return `<<${place.type}_${place.id.slice(2).padEnd(8, '0').slice(0, 8)}>>`;
}

function findings() {
	const list = LETTER.places.map((place) => ({
		id: place.id,
		kind: 'confirmed',
		type: place.type,
		category: place.category,
		score: place.question ? 0.5 : 0.97,
		...section(place),
		text: place.value,
		context: { before: '', match: place.value, after: '' },
		source: 'ner',
		detector: 'test',
		review_required: place.question !== undefined,
		auto_accepted: place.question === undefined,
		question: place.question ?? null,
		assessment: null
	}));
	return {
		job_id: 'j-w',
		offset_encoding: 'utf-16',
		text: LETTER.text,
		confirmed: list,
		suspicious: [],
		findings: list,
		blocks: [{ index: 0, start: 0, end: LETTER.text.length, kind: 'paragraph', page: null }],
		counts: {
			confirmed: list.length,
			suspicious: 0,
			total: list.length,
			by_entity: {},
			by_category: { names: 1, addresses: 1, contact: 4 },
			questions: 1
		}
	};
}

/** Apply small-scale masking: insert codes for all findings. */
function apply() {
	const places = LETTER.places
		.map((place) => ({ place, ...section(place) }))
		.sort((a, b) => a.start - b.start);
	let text = '';
	let cursor = 0;
	const applied = places.map(({ place, start, end }) => {
		text += LETTER.text.slice(cursor, start);
		const output_start = text.length;
		text += code(place);
		cursor = end;
		return {
			finding_id: place.id,
			kind: 'confirmed',
			entity_type: place.type,
			category: place.category,
			source: 'ner',
			mode: 'token_deterministic',
			reversibility: 'vault',
			original_start: start,
			original_end: end,
			output_start,
			output_end: text.length
		};
	});
	text += LETTER.text.slice(cursor);
	return {
		offset_encoding: 'utf-16',
		text,
		masking: { method: 'reversible', style: 'codes', categories: [], anonymize: false },
		labels: {
			label: 'reversible',
			contains_surrogates: false,
			anonymous_blockers: ['not_requested'],
			protection_level: 2,
			kept_here_count: 0,
			masked_without_decision: 1
		},
		applied_findings: applied,
		applied_by_category: {},
		residual_risk: { status: 'not_run', heuristic: true, threshold: 2, classes: [], counts: {} },
		facts: {},
		report: {},
		job_id: 'j-w',
		entry_id: 'e-w',
		placements: []
	};
}

const ENTRY = entry({
	id: 'e-w',
	title: 'Brief',
	status: 'review',
	files: [
		{
			id: 'j-w',
			name: 'brief.docx',
			format: 'docx',
			size_bytes: PREVIEW.length,
			pages: null,
			ocr_used: false,
			status: 'review',
			error_code: null,
			counts: {},
			label: null,
			output_path: null
		}
	]
});

async function wordHarness(
	context: Parameters<typeof harness>[0],
	{
		withoutPreview = false,
		pageFaithful
	}: { withoutPreview?: boolean; pageFaithful?: 'da' | 'kaputt' } = {}
) {
	return harness(context, {
		entries: () => [ENTRY],
		sidecar: (method, path, _body, search) => {
			if (path === '/entries/e-w' && method === 'GET') return ENTRY;
			if (path === '/entries/e-w/progress') {
				return {
					entry_id: 'e-w',
					status: 'review',
					files: [],
					totals: {},
					done: 1,
					total: 1,
					ready: true
				};
			}
			if (!path.startsWith('/jobs/j-w/')) return undefined;
			if (path.endsWith('/findings')) return findings();
			if (path.endsWith('/layout')) {
				return { job_id: 'j-w', ...LETTER.layout, paged: pageFaithful !== undefined };
			}
			if (path.includes('/layout/paged')) {
				if (pageFaithful !== 'da') return undefined;
				const docPage =
					new URLSearchParams(search).get('side') === 'original' ? 'original' : 'result';
				if (path.endsWith('/layout/paged')) return { job_id: 'j-w', ...PAGE_FAITHFUL[docPage] };
				return new Roh(PAGE_FAITHFUL_IMAGE[docPage], 'image/png');
			}
			if (path.endsWith('/layout/document')) {
				return withoutPreview ? undefined : new Roh(PREVIEW, DOCX);
			}
			if (path.endsWith('/apply')) return apply();
			return undefined;
		}
	});
}

/** The interactive island (right side when shown side-by-side). */
function island(page: Page): FrameLocator {
	return page.frameLocator('iframe:not([aria-hidden="true"])');
}

async function islandReady(page: Page): Promise<void> {
	await expect(island(page).locator('section.docx').first()).toBeVisible();
	await expect(island(page).locator('.unn-code').first()).toBeVisible();
}

test('Word: pages, table, header/footer, codes in place', async ({ context, page }) => {
	await wordHarness(context);
	await open(page, '/entry/e-w/review');
	await islandReady(page);
	const doc = island(page);

	await expect(doc.locator('header').first()).toContainText('Moebelhaus Online Shop');
	await expect(doc.locator('footer').first()).toContainText('Ihr Online Team');
	await expect(doc.locator('table').first()).toContainText('Armlehnstuhl Giant');
	// No simplified paragraph, no error.
	await expect(page.getByRole('note')).toHaveCount(0);
	await expect(page.getByRole('alert')).toHaveCount(0);

	// Codes replace values – first run (bold first name), in link text, in header/footer.
	for (const place of LETTER.places.filter((s) => !s.question)) {
		await expect(doc.getByText(code(place), { exact: true })).toBeVisible();
	}
	await expect(doc.locator('body')).not.toContainText('Mustergasse');
	const name = doc.getByRole('button', { name: /Mustermann/ });
	expect(
		await name.evaluate((element) => getComputedStyle(element.parentElement!).fontWeight)
	).toBe('700');
	// The open question remains readable, with its number.
	await expect(doc.locator('.unn-question')).toHaveText(LETTER.places[2].value);
	await expect(doc.locator('sup[data-addition]')).toHaveText('1');

	// The island runs without scripts and without external targets.
	const iframe = page.locator('iframe:not([aria-hidden="true"])');
	await expect(iframe).toHaveAttribute('sandbox', 'allow-same-origin');

	await board(page, 'layout-word');

	// Space bar: show original without codes.
	await page.locator('body').click({ position: { x: 5, y: 400 } });
	await page.keyboard.down('Space');
	await expect(doc.locator('.unn-code')).toHaveCount(0);
	await expect(doc.locator('body')).toContainText('Mustergasse 12/1/30');
	await page.keyboard.up('Space');
	await expect(doc.locator('.unn-code').first()).toBeVisible();
});

test('Word: code menu via keyboard, focus back to island, Alt+N', async ({ context, page }) => {
	const { capture } = await wordHarness(context);
	await open(page, '/entry/e-w/review');
	await islandReady(page);
	const name = island(page).getByRole('button', { name: /Mustermann/ });

	await name.focus();
	await page.keyboard.press('Enter');
	const menu = page.getByRole('menu');
	await expect(menu).toBeVisible();
	// The menu attaches to the code in the island.
	const button = (await name.boundingBox())!;
	const kiste = (await menu.boundingBox())!;
	expect(Math.abs(kiste.y - (button.y + button.height))).toBeLessThan(40);
	await page.keyboard.press('Escape');
	await expect(menu).toBeHidden();
	await expect(name).toBeFocused();

	// Click opens the same menu; "Keep only here" is sent as the decision to apply.
	await name.click();
	await page.getByRole('menuitem', { name: 'Nur hier behalten' }).click();
	await expect(menu).toBeHidden();
	await expect
		.poll(() =>
			capture.requests.some(
				(request) =>
					request.path.endsWith('/apply') &&
					JSON.stringify(request.body).includes('"finding_id":"f_name","action":"reject"')
			)
		)
		.toBe(true);

	// Alt+N – also from the island – fetches the open question.
	await island(page).locator('.unn-code').first().focus();
	await page.keyboard.press('Alt+KeyN');
	await expect(page.locator('[data-question="f_tel"] button').first()).toBeFocused();
});

