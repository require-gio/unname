DESCRIPTION_MAP = {
    "de": {
        "P": {"f": "Person (Frau)", "m": "Person (Herr)", "x": "Person"},
        "F": "Firma",
        "X": "Produkt oder Marke",
        "O": "Ort oder Region",
    },
    "en": {
        "P": {"f": "person (woman)", "m": "person (man)", "x": "person"},
        "F": "company",
        "X": "product or brand",
        "O": "place or region",
    },
}
LABEL_VON = {
    "P": "person",
    "F": "organization_or_product",
    "X": "organization_or_product",
    "O": "location",
}
_PLACEHOLDER_REGEX = re.compile(r"\{([PFXO])(\d+)\}")


def _person(fake: Faker, rng: random.Random, language: str) -> tuple[str, str]:
    geschlecht = rng.choice("fm")
    vorname = fake.first_name_female() if geschlecht == "f" else fake.first_name_male()
    zufall = rng.random()
    if zufall < 0.3:
        nachname = rng.choice(RARE_LAST_NAMES)
    elif zufall < 0.45:
        nachname = rng.choice(WORD_LAST_NAMES)
    else:
        nachname = fake.last_name()
    form = rng.random()
    if form < 0.6:
        val = f"{vorname} {nachname}"
    elif form < 0.8:
        title = rng.choice(
            ("Mag.", "Dr.", "DI", "Ing.", "Prof.")
            if language == "de"
            else ("Dr", "Prof.", "Mr", "Ms")
        )
        val = f"{title} {vorname} {nachname}"
    else:
        # Only the last name: as it appears after “Herr”/“Frau” in the text.
        val = nachname
    return val, geschlecht


def _company(fake: Faker, rng: random.Random, language: str) -> str:
    zufall = rng.random()
    if zufall < 0.35:
        return f"{rng.choice(BRANCHEN[language])} {fake.last_name()} {rng.choice(RECHTSFORMEN[language])}"
    if zufall < 0.55:
        nachname = rng.choice(RARE_LAST_NAMES + WORD_LAST_NAMES)
        if language == "de":
            pattern = rng.choice(("Gebrüder {n}", "{n} & Söhne", "{n} Holzbau", "{n} Bräu"))
        else:
            pattern = rng.choice(("{n} & Sons", "{n} Brothers", "{n} Timber", "{n} Brewing"))
        return pattern.format(n=nachname)
    if zufall < 0.8:
        return fake.company()
    # Artificial names without legal form – the hardest for detection.
    return f"{rng.choice(PRODUKT_SILBEN)}{rng.choice(PRODUCT_SUFFIXES)}"


def _produkt(rng: random.Random) -> str:
    stem = f"{rng.choice(PRODUKT_SILBEN)}{rng.choice(PRODUCT_SUFFIXES)}"
    return stem if rng.random() < 0.3 else f"{stem} {rng.choice(PRODUCT_ADDITIONS)}"


def _place(fake: Faker, rng: random.Random, language: str) -> str:
    if rng.random() < 0.35:
        return rng.choice(EXTRA_LOCATIONS[language])
    return fake.city()


def design(number: int, language: str, seed: int) -> dict:
    """Determine document type, length and placeholders based on the seed."""

    rng = random.Random(seed)
    fake = Faker(rng.choice(FAKER_LOCALES[language]))
    fake.seed_instance(seed)
    values: dict[str, dict] = {}
    description_text = DESCRIPTION_MAP[language]
    for art, item_count in (
        ("P", rng.randint(2, 4)),
        ("F", rng.randint(1, 3)),
        ("X", rng.randint(0, 2)),
        ("O", rng.randint(1, 3)),
    ):
        for index in range(1, item_count + 1):
            if art == "P":
                val, geschlecht = _person(fake, rng, language)
                text = description_text["P"][geschlecht if " " not in val else "x"]
                if " " not in val:
                    text = description_text["P"][geschlecht] + (
                        ", nur Nachname" if language == "de" else ", surname only"
                    )
            elif art == "F":
                val, text = _company(fake, rng, language), description_text["F"]
            elif art == "X":
                val, text = _produkt(rng), description_text["X"]
            else:
                val, text = _place(fake, rng, language), description_text["O"]
            values[f"{art}{index}"] = {"wert": val, "beschreibung": text}
    return {
        "id": f"{language}-{number:04d}",
        "sprache": language,
        "art": rng.choice(KIND_TYPES[language]),
        "woerter": rng.choice((120, 180, 250)),
        "platzhalter": values,
        "seed": seed,
    }


def einsetzen(roh: str, placeholders: dict[str, dict]) -> tuple[str, list[dict]]:
    """Insert values and record gold spans (Python offsets)."""

    roh = roh.replace("**", "").replace("__", "")
    roh = re.sub(r"^#+\s*", "", roh, flags=re.MULTILINE).strip()
    parts: list[str] = []
    spannen: list[dict] = []
    position = 0
    length = 0
    for match in _PLACEHOLDER_REGEX.finditer(roh):
        key = f"{match.group(1)}{match.group(2)}"
        if key not in placeholders:
            raise ValueError(f"unbekannter Platzhalter {key}")
        prefix_text = roh[position : match.start()]
        parts.append(prefix_text)
        length += len(prefix_text)
        val = placeholders[key]["wert"]
        spannen.append(
            {
                "start": length,
                "end": length + len(val),
                "label": LABEL_VON[match.group(1)],
                "platzhalter": key,
            }
        )
        parts.append(val)
        length += len(val)
        position = match.end()
    parts.append(roh[position:])
    text = "".join(parts)
    if "{" in text or "}" in text:
        raise ValueError("Klammern im Text uebrig")
    used_placeholders = {spanne["platzhalter"] for spanne in spannen}
    if not used_placeholders:
        raise ValueError("kein Platzhalter benutzt")
    return text, spannen


def generate(draft: dict, model_name: str) -> dict:
    language = draft["sprache"]
    list_text = "\n".join(
        f"- {{{key}}}: {entry['beschreibung']}" for key, entry in draft["platzhalter"].items()
    )
    task = TASK_TEMPLATE[language].format(
        art=draft["art"], words=draft["woerter"], placeholders=list_text
    )
    last_error = ""
    for versuch in range(3):
        roh = chat(
            model_name,
            SYSTEM[language],
            task,
            temperature=0.9,
            seed=draft["seed"] + versuch,
        )
        try:
            text, spannen = einsetzen(roh, draft["platzhalter"])
        except ValueError as error:
            last_error = str(error)
            continue
        return {
            "id": draft["id"],
            "sprache": language,
            "art": draft["art"],
            "text": text,
            "gold": spannen,
            "modell": model_name,
        }
    raise RuntimeError(f"{draft['id']}: {last_error}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default="gemma4:26b-nvfp4")
    parser.add_argument("--count", type=int, default=320, help="Dokumente, je zur Haelfte DE/EN")
    parser.add_argument("--parallel", type=int, default=3)
    parser.add_argument("--output", type=Path, default=Path("testdata/zweitmeinung/korpus.jsonl"))
    args = parser.parse_args(argv)
    check_local(args.model)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    completed: set[str] = set()
    if args.output.exists():
        for line in args.output.read_text(encoding="utf-8").splitlines():
            if line.strip():
                completed.add(json.loads(line)["id"])
    drafts = [
        design(number, language, seed=number * 2 + (language == "en"))
        for number in range(args.count // 2)
        for language in ("de", "en")
    ]
    open_items = [draft for draft in drafts if draft["id"] not in completed]
    print(f"{len(completed)} vorhanden, {len(open_items)} offen", flush=True)
    lock = threading.Lock()
    beginn = time.monotonic()
    error = 0
    with (
        ThreadPoolExecutor(args.parallel) as pool,
        args.output.open("a", encoding="utf-8") as file_path,
    ):
        tasks = {pool.submit(generate, draft, args.model): draft for draft in open_items}
        for index, task in enumerate(as_completed(tasks), 1):
            try:
                document = task.result()
            except Exception as ausnahme:  # noqa: BLE001 – a document may fail
                error += 1
                print(f"  verworfen: {ausnahme}", file=sys.stderr, flush=True)
                continue
            with lock:
                file_path.write(json.dumps(document, ensure_ascii=False, sort_keys=True) + "\n")
                file_path.flush()
            if index % 20 == 0:
                duration = time.monotonic() - beginn
                print(
                    f"  {index}/{len(open_items)} · {duration / index:.1f} s je Dokument",
                    flush=True,
                )
    print(f"fertig, {error} verworfen")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
