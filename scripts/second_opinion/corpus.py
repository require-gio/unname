"""Step 1: generate synthetic business texts with exact gold spans.

A local LLM writes letters, contracts, invoices, e-mails … in German and English.
Names, companies, products and places are not generated by the model itself:
it receives placeholders (``{P1}``, ``{F1}``, ``{O1}``) with short descriptions,
and this script inserts fabricated values. Thus the gold data is exact – a span
represents a person, company/product or location only when it originates from a
placeholder. Everything else is treated as a generic term.

Free marking by the LLM was abandoned on 2026-10-25: it marked
“Zirbenholz” and “Eichen-Esstische” as companies.

The values mix common and unusual names, companies with and without legal form,
invented products, locations from DE/AT/UK/US and surnames that are also words
(Koch, Winter, Fuchs) – the edge cases where detection becomes uncertain.
The LLM should also use many uppercase technical terms, headings, departments
and standards: they are typical false positives in the review step.

Run from the repository root; it resumes where it left off:

    uv run --project sidecar python -m scripts.second_opinion.corpus \\
        --model gemma4:26b-nvfp4 --count 320 \\
        --output testdata/zweitmeinung/korpus.jsonl
"""

