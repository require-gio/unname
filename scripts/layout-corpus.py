def page_faithful_fixtures(path: Path, target_path: Path) -> None:
    """Word page-faithful: cards and page images of original and result.

    Only works with the Office engine (``office_engine.py``); otherwise the
    stored fixtures stay unchanged. Generated with the same functions as
    ``GET /jobs/{id}/layout/paged``.
    """

    import json

    from presidio_sidecar.document_workflow import docx_result_bytes
    from presidio_sidecar.extraction import DocumentExtractor
    from presidio_sidecar.office_engine import docx_to_pdf, office_engine
    from presidio_sidecar.paged_docx import paged_layout, side_units
    from presidio_sidecar.rendering import render_pdf_bytes_png

    engine = office_engine()
    if engine is None:
        print("Keine Office-Engine: brief-seitentreu* bleibt unveraendert.")
        return
    document_obj = DocumentExtractor().extract_bytes(path.read_bytes(), filename=path.name)
    result = result_for(document_obj, LETTER_PLACES)
    maps: dict[str, object] = {}
    for page_obj, name, processing_step in (
        ("original", "original", None),
        ("result", "ergebnis", result),
    ):
        docx = docx_result_bytes(
            path,
            document=document_obj,
            source_text=document_obj.text,
            processing=processing_step,  # type: ignore[arg-type]
        )
        pdf = docx_to_pdf(engine, docx)
        units = side_units(document_obj, document_obj.text, page_obj, processing_step)  # type: ignore[arg-type]
        layout_map = paged_layout(pdf, units, document_obj.text, max_image_pixels=10**8)
        maps[page_obj] = {
            "side": page_obj,
            "revision": 0 if page_obj == "original" else 1,
            "engine": {"name": engine.name, "version": engine.version},
            "offset_encoding": "utf-16",
            **layout_map,
        }
        for number in range(len(layout_map["pages"])):
            (target_path / f"brief-seitentreu-{name}-{number}.png").write_bytes(
                render_pdf_bytes_png(pdf, number, 1.0, max_image_pixels=10**8)
            )
    (target_path / "brief-seitentreu.json").write_text(
        json.dumps(maps, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )


