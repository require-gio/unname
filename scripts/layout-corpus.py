def smoke_code(place: dict[str, object]) -> str:
    """Code inserted by the Apply mock in ``layout.spec.ts``."""

    identifier = str(place["id"])[2:].ljust(8, "0")[:8]
    return f"<<{place['type']}_{identifier}>>"


def place_range(text: str, place: dict[str, object]) -> tuple[int, int]:
    """Range of an entry in the source text: first occurrence, optionally after ``nach``."""

    ab = text.index(str(place["after"])) if "after" in place else 0
    start = text.index(str(place["value"]), ab)
    return start, start + len(str(place["value"]))


def result_for(document_obj: object, places: tuple[dict[str, object], ...]) -> object:
    """Small Apply result: each entry replaced by its code."""

    from types import SimpleNamespace

    from presidio_sidecar.processing import (
        AppliedFinding,
        FindingKind,
        ProcessingMode,
        Reversibility,
    )

    text = document_obj.text  # type: ignore[attr-defined]
    areas = sorted((place_range(text, place), place) for place in places)
    output = ""
    cursor = 0
    angewandt = []
    for (start, end_pos), place in areas:
        output += text[cursor:start]
        start_idx = len(output)
        output += smoke_code(place)
        cursor = end_pos
        angewandt.append(
            AppliedFinding(
                finding_id=str(place["id"]),
                kind=FindingKind.CONFIRMED,
                entity_type=str(place["type"]),
                source="ner",
                score=1.0,
                mode=ProcessingMode.TOKEN_DETERMINISTIC,
                reversibility=Reversibility.VAULT,
                original_start=start,
                original_end=end_pos,
                output_start=start_idx,
                output_end=len(output),
            )
        )
    output += text[cursor:]
    # No dataclass: tests import this script without a sys.modules entry.
    return SimpleNamespace(text=output, applied_findings=tuple(angewandt))


def smoke_result(document_obj: object) -> object:
    """Apply result for the smoke test: each entry replaced by its code."""

    return result_for(document_obj, SMOKE_PLACES)


def smoke_placements(document_obj: object, path: Path) -> list[dict[str, object]]:
    """Placement plan for the smoke test entries as provided by Apply."""

    from presidio_sidecar.document_workflow import pdf_page_geometry, plan_placements

    return plan_placements(
        document_obj,  # type: ignore[arg-type]
        document_obj.text,  # type: ignore[attr-defined]
        smoke_result(document_obj),  # type: ignore[arg-type]
        lambda page_obj: pdf_page_geometry(path, page_obj),
    )


