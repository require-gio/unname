def delivery_note_pdf(*, rotation: int = 0, cropbox: bool = False) -> bytes:
    document = fitz.open()
    page = document.new_page(width=A4[0], height=A4[1])
    delivery_note_page(page)
    if cropbox:
        page.set_cropbox(fitz.Rect(20, 30, 575, 812))
    if rotation:
        page.set_rotation(rotation)
    payload = document.tobytes(garbage=3, deflate=True)
    document.close()
    return payload


def _page_image(dpi: int) -> Image.Image:
    document = fitz.open(stream=delivery_note_pdf(), filetype="pdf")
    pixmap = document[0].get_pixmap(dpi=dpi, colorspace=fitz.csRGB, alpha=False)
    image = Image.frombytes("RGB", (pixmap.width, pixmap.height), pixmap.samples)
    document.close()
    return image


def _verrauscht(image: Image.Image, *, keim: int) -> Image.Image:
    zufall = random.Random(keim)
    rauschen = Image.effect_noise(image.size, 18).convert("RGB")
    gemischt = Image.blend(image, rauschen, 0.06)
    # Add slight blur and a small tilt to mimic a flatbed scanner.
    gemischt = gemischt.filter(ImageFilter.GaussianBlur(0.4))
    winkel = 0.8 + zufall.random() * 0.4
    return gemischt.rotate(winkel, resample=Image.BICUBIC, fillcolor="white")


def _jpeg(image: Image.Image, **zusatz: object) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, format="JPEG", quality=72, **zusatz)
    return buffer.getvalue()


def scan_pdf(*, rotation: int = 0) -> bytes:
    image_bytes = _jpeg(_verrauscht(_page_image(150), keim=1110))
    document = fitz.open()
    page = document.new_page(width=A4[0], height=A4[1])
    page.insert_image(page.rect, stream=image_bytes)
    if rotation:
        page.set_rotation(rotation)
    payload = document.tobytes(garbage=3, deflate=True)
    document.close()
    return payload


def _crop() -> Image.Image:
    # Header and address at 200 dpi are large enough for Tesseract.
    image_bytes = _page_image(200)
    faktor = 200 / 72
    return image_bytes.crop(tuple(round(val * faktor) for val in (40, 150, 560, 290)))


def photo_exif6() -> bytes:
    # Orientation 6: rotate the stored image 90° clockwise for display.
    # The image is saved with a counter-clockwise rotation flag.
    aufrecht = _verrauscht(_crop(), keim=6)
    stored = aufrecht.rotate(90, expand=True)
    exif = Image.Exif()
    exif[0x0112] = 6
    return _jpeg(stored, exif=exif.tobytes())


def screenshot() -> bytes:
    buffer = io.BytesIO()
    _crop().save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def _hyperlink(paragraph: object, text: str, target_path: str) -> None:
    """Create an external hyperlink – the preview copy must remove it."""

    from docx.opc.constants import RELATIONSHIP_TYPE
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn

    relationship = paragraph.part.relate_to(
        target_path, RELATIONSHIP_TYPE.HYPERLINK, is_external=True
    )  # type: ignore[attr-defined]
    link = OxmlElement("w:hyperlink")
    link.set(qn("r:id"), relationship)
    run = OxmlElement("w:r")
    font_elem = OxmlElement("w:t")
    font_elem.text = text
    run.append(font_elem)
    link.append(run)
    paragraph._p.append(link)  # type: ignore[attr-defined]  # noqa: SLF001


