"""Synthetic corpus for the layout-accurate preview (Layout-Plan, Phase M).

Creates documents under ``testdata/layout/`` that cover the cases from finding 1.4
without real personal data:

- ``lieferschein.pdf``: replica of ``testdata/regression/lieferschein-moebelhaus.txt``
  with header, table with lines, footer and white control text at 0.96 pt;
  the same page rotated (``lieferschein-rot90/180/270.pdf``) and with
  a CropBox offset (``lieferschein-cropbox.pdf``)
- ``scan.pdf`` / ``scan-rot90.pdf``: the same page rasterised, slightly skewed,
  with JPG noise, no text layer; once additionally with ``/Rotate 90``
- ``foto-exif6.jpg``: excerpt as a photo with EXIF orientation 6
- ``bildschirmfoto.png``: excerpt as PNG
- ``brief.docx``: letter with header/footer, table, tabs, numbering,
  name spanning two runs, line break in paragraph and external hyperlink
- ``kunden.xlsx``: merged cells, number formats, frozen row,
  hidden column, borders, row height, conditional formatting and a
  second sheet with wrap and formula; ``kunden.csv``

Generation is deterministic (fixed random seed). Tests call
``erzeugen(ziel)`` with a temporary folder instead of reading the stored
files; the repository files are for viewing and manual sampling.

With ``--smoke`` the Playwright test fixtures are also created
(``app/tests/smoke/fixtures/layout/``): layout map, page image,
placement plan and control image (``*-ergebnis.png``), generated by the real
Sidecar code; for Word the preview copy of the letter and that of the
saved file (``brief-*.docx``, spec §2), plus a long letter without saved
page breaks (``lang*``) and – if an Office engine is present – the page-accurate
view of the letter (``brief-seitentreu*``, Phase S). Scans run through a
fixed OCR that reports the words of the replica – Tesseract is not needed.

``SehendeOcr`` (Phase P) reads instead what is actually in the image: a word
only while its pixels are untouched, a code only where new ink is present.
Thus tests and ``llm-round-trip.py --scan`` verify the scan export together
with the Ruecklese check without Tesseract.

Run from the repository:
    uv run --project sidecar python scripts/layout-corpus.py [--ziel testdata/layout] [--smoke]
"""

