def letter_fixtures(path: Path, target_path: Path) -> None:
    """Word probe: layout map, preview copy and preview of the saved file.

    The saved file is produced via the real export
    (``export_processed_document``); its preview copy carries the same
    anchors. This lets ``flow-anchor.spec.ts`` compare unit by unit that the
    replacement appears in the view at the same location as in the file.
    """

    import json
    import tempfile

    from presidio_sidecar.document_workflow import export_processed_document
    from presidio_sidecar.docx_preview import build_docx_preview
    from presidio_sidecar.extraction import DocumentExtractor
    from presidio_sidecar.extraction.docx_units import docx_units
    from presidio_sidecar.layout import build_layout, docx_unit_segments

    document_obj = DocumentExtractor().extract_bytes(path.read_bytes(), filename=path.name)
    layout = build_layout("brief", document_obj, path, max_image_pixels=10**8)
    units = [document_obj.text[s.start : s.end] for s in docx_unit_segments(document_obj)]
    (target_path / "brief-vorschau.docx").write_bytes(build_docx_preview(path, units))
    with tempfile.TemporaryDirectory() as folder:
        stored = Path(folder) / "brief_geschuetzt.docx"
        export_processed_document(
            path,
            stored,
            document=document_obj,
            source_text=document_obj.text,
            processing=result_for(document_obj, LETTER_PLACES),  # type: ignore[arg-type]
        )
        from docx import Document

        texts = [unit.text for unit in docx_units(Document(stored))]
        (target_path / "brief-ergebnis-vorschau.docx").write_bytes(
            build_docx_preview(stored, texts)
        )
    (target_path / "brief.json").write_text(
        json.dumps(
            {"text": document_obj.text, "layout": layout, "places": LETTER_PLACES},
            ensure_ascii=False,
            separators=(",", ":"),
        )
        + "\n",
        encoding="utf-8",
    )


