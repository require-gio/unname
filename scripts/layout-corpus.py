def generate(target_path: Path, only_names: tuple[str, ...] | None = None) -> dict[str, Path]:
    """Writes the corpus files to ``ziel``; ``namen`` selects which ones."""

    target_path.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    for name, build in FILES.items():
        if only_names is not None and name not in only_names:
            continue
        path = target_path / name
        path.write_bytes(build())
        written[name] = path
    return written


class _ReplikOcr:
    """Report OCR words of the replica at their image positions."""

    def recognize(self, image: Image.Image, *, languages: tuple[str, ...]) -> tuple:
        from presidio_sidecar.extraction import OcrWord

        document = fitz.open(stream=delivery_note_pdf(), filetype="pdf")
        page = document[0]
        faktor = image.width / page.rect.width
        words = []
        for x0, y0, x1, y1, text, block, line, _ in page.get_text("words", sort=True):
            if y1 - y0 < 2:  # Header text: not part of OCR
                continue
            words.append(
                OcrWord(
                    text,
                    left=round(x0 * faktor),
                    top=round(y0 * faktor),
                    width=max(1, round((x1 - x0) * faktor)),
                    height=max(1, round((y1 - y0) * faktor)),
                    line_id=(1, block, 1, line),
                    confidence=0.9,
                )
            )
        document.close()
        return tuple(words)


#: Median gray-value deviation below which a region is considered unchanged.
#: A slightly different zoom shifts edges (few gray levels); a removed or overpainted word deviates
#: many times.
_UNTOUCHED = 12


class SehendeOcr:
    """Read a scan of the replica as it currently appears.

    ``source_path`` is the untouched scan. A word from the replica is reported only
    if the pixels under its box still match the original; a code from ``codes``
    (value, box in display space points) is reported only if new ink is present.
    This provides the mandatory export check on real pixels – without Tesseract.
    Tests and ``llm-round-trip.py --scan`` use it.
    """

    def __init__(
        self,
        source_path: Path,
        codes: list[tuple[str, tuple[float, ...]]] | None = None,
    ) -> None:
        self.source_path = source_path
        self.codes = list(codes or [])
        self.calls = 0
        with fitz.open(source_path) as scan:
            page_obj = scan[0]
            self.size_px = (page_obj.rect.width, page_obj.rect.height)
            page_rotation = page_obj.rotation_matrix
        replik = fitz.open(stream=delivery_note_pdf(), filetype="pdf")
        self.words = [
            (str(text), fitz.Rect(x0, y0, x1, y1) * page_rotation, (block, line))
            for x0, y0, x1, y1, text, block, line, _ in replik[0].get_text("words", sort=True)
            if y1 - y0 >= 2  # Small header text (0.96 pt) is not read by OCR
        ]
        replik.close()
        self._originals: dict[tuple[int, int], Image.Image] = {}

    def _original(self, size_px: tuple[int, int]) -> Image.Image:
        if size_px not in self._originals:
            with fitz.open(self.source_path) as scan:
                zoom = size_px[0] / scan[0].rect.width
                pixmap = scan[0].get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
            image_bytes = Image.frombytes("RGB", (pixmap.width, pixmap.height), pixmap.samples)
            self._originals[size_px] = image_bytes.resize(size_px).convert("L")
        return self._originals[size_px]

    def recognize(self, image: Image.Image, *, languages: tuple[str, ...]) -> tuple:
        from PIL import ImageChops, ImageStat

        from presidio_sidecar.extraction import OcrWord

        del languages
        self.calls += 1
        grau = image.convert("L")
        original = self._original(grau.size)
        faktor = grau.width / self.size_px[0]

        def pixel(rect: fitz.Rect) -> tuple[int, int, int, int]:
            return tuple(round(val * faktor) for val in rect)  # type: ignore[return-value]

        def deviation(box: tuple[int, int, int, int]) -> float:
            return ImageStat.Stat(ImageChops.difference(grau.crop(box), original.crop(box))).mean[0]

        def word(text: str, rect: fitz.Rect, line: tuple[int, int]) -> OcrWord:
            left_coord, top_coord, right_coord, bottom_coord = pixel(rect)
            return OcrWord(
                text,
                left=left_coord,
                top=top_coord,
                width=max(1, right_coord - left_coord),
                height=max(1, bottom_coord - top_coord),
                line_id=(1, line[0], 1, line[1]),
                confidence=0.9,
            )

        found = [
            word(text, rect, line)
            for text, rect, line in self.words
            if deviation(pixel(rect)) < _UNTOUCHED
        ]
        for number, (text, box) in enumerate(self.codes):
            rect = fitz.Rect(box)
            crop_region = grau.crop(pixel(rect))
            tinte = (
                sum(crop_region.histogram()[:128]) > 0.02 * crop_region.width * crop_region.height
            )
            if tinte and deviation(pixel(rect)) >= _UNTOUCHED:
                found.append(word(text, rect, (900 + number, 1)))
        return tuple(found)


def code_areas(placements: list[dict]) -> list[tuple[str, tuple[float, ...]]]:
    """Map code positions from the placement plan for :class:`SehendeOcr`.

    The first area of a location (display space) carries the code – also on
    rotated pages where it runs vertically in the display space.
    """

    return [
        (placement["text"]["value"], tuple(placement["cover"][0]))
        for placement in placements
        if placement["text"] is not None
    ]


